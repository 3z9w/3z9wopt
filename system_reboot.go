package main

// ============================================================================
// 「重启，把最后一批拿回来」—— 立即重启（2026-10-15 新增，2026-10-16 定型）
//
// 【为什么要有这个】
// 真机二连清时发现的现象（当天 %TEMP%\3z9wOptV11_clean_trace.log 取证）：
//   第二轮清出来 freed=30.3 MB，left=274 MB；probe 明细写着
//   thumb 30/30 被占、deepjunk 118/137 被占 —— **剩下这批恰恰是正在跑的程序自己生成并攥着的**。
// 不关它们就删不动，唯一的出路是 MoveFileEx 排进系统队列、下次启动早阶段由 smss.exe 删掉
// （junk_rebootdel.go，微软 MoveFileEx 文档里写明的机制）。
// 可多数用户看到"下次开机自动删"不会马上关机，这笔空间就一直悬着，
// 而 PendingFileRenameOperations 久挂着对 Windows 更新也不友好。
// → 完成页要给用户一个"现在就重启把它拿回来"的出口。
//
// 【为什么只剩「立即重启」一条路（2026-10-16 用户拍板）】
//   原来给的是「缓冲 10 秒 + 倒计时可取消」，用户原话：
//     「有了立即重启按钮之后，10 秒后重启简直就是画蛇添足，直接删掉」。
//   这话是对的 —— 缓冲的全部意义只是"手滑能反悔"，而那件事**确认框已经在做**，
//   倒计时等于在同一个决定上问第二遍，纯属拖着人。
//   ⚠️ 所以缓冲那一整套（rebootCmdArgs / ScheduleReboot / CancelReboot + 前端
//      rbGo / rbTick / rbCancel / 倒计时）是**连根删掉**的，不是藏在哪儿 ——
//      谁要加回来，先看当天的用户原话和上面这段。
//   ⚠️「不默默重启」这条底线**没变**，只是落点变了：
//      从"倒计时"挪到了**前端那个确认框**（见 RebootNow 的调用契约）。
//
// 【三条硬规矩（都不是拍脑袋）】
//   1. 绝不默默重启 —— 唯一入口 RebootNow()，前端必须先弹确认框。
//   2. 走系统自带的 shutdown.exe，路径用 sysExe()：精简版/企业锁 PATH 的机器裸命令会
//      exec: not found（铁律一）。外部命令必须 HideWindow（铁律三）。
//   3. shutdown 只是"安排"一个系统状态，调用本身秒回 —— 这里**不许**等待机器真的重启。
// ============================================================================

import (
	"context"
	"fmt"
	"time"
)

// rebootImmediateArgs 立即重启的参数。
//
// 为什么单独成一个函数、不并进某个通用的参数构造函数：
// /t 0 是**唯一一个不给反悔机会**的形态。放在一个谁都能调的通用函数里迟早出事
// （有人传个 0 进去，用户手一滑机器就没了）。单独立出来，守门测试才能一句话锁死：
// 本文件里 "/t" 只许出现这一次。
//
// 不带 /f：不给缓冲说的是"别让用户等"，不是"别让他的 Word 问要不要保存"。
// 少了 /f，没保存的程序还能把用户拦下来 —— 那是 Windows 本来该做的事，我们不替用户决定。
func rebootImmediateArgs() []string {
	return []string{"/r", "/t", "0", "/c", "3z9wOpt：重启后完成最后一批垃圾清理"}
}

// RebootNow 重启电脑（立即，无倒计时）。
//
// 🔴 调用契约：**前端必须先弹确认框，用户点「确定」才能调它**。
// 这条契约后端兜不住（后端没法弹窗），所以守门测试改成守住"唯一出口"这件事：
// /t 0 只可能出自本文件的 rebootImmediateArgs，且本文件里没有第二条构造重启参数的路。
// 守住那段测试的人（包括未来的自己），请顺手守住前端那个确认框 ——
// 那才是"不默默重启"的真正落点；删了它，这个函数就变成一颗子弹。
func (a *App) RebootNow() string {
	args := rebootImmediateArgs()
	if err := runHiddenCtx(context.Background(), 15*time.Second, sysExe("shutdown.exe", ""), args...); err != nil {
		/* 常见成因是被组策略禁用了关机权限，不是磁盘也不是软件坏了 —— 说错归因用户会瞎猜。 */
		cleanTrace(fmt.Sprintf("重启失败: %v", err))
		return "没能重启（这台机器可能禁止程序触发重启）"
	}
	cleanTrace("已安排立即重启（用户点了「立即重启」并确认）")
	return ""
}
